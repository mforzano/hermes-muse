def watch_instructions(key, goal_id):
    return ("Check its status and your stop condition first. Prepare evidence with notification_add. "
            "Stop and call watch_stop when the promised condition is satisfied. "
            f"Before final preparation, call review_complete with job={key}, goal_id={goal_id}, "
            "stop_condition copied exactly from below, source_check_ids from this run's actual reads, and summary. "
            "Then call run_complete with outcome/summary/gaps only; use partial for unfinished coverage. "
            "As your last step call notification_prepare and return its final_response exactly; "
            "this job delivers that response. With nothing approved return [SILENT].\n")


@contextmanager
def profile_scope(home):
    from hermes_constants import set_hermes_home_override, reset_hermes_home_override
    token = set_hermes_home_override(home)
    try:
        yield
    finally:
        reset_hermes_home_override(token)


from .locks import file_lock


class HermesHost:
    def __init__(self, store, plugin_root=ROOT):
        self.store, self.home, self.root = store, store.home, Path(plugin_root).resolve()

    def manifest(self):
        path = self.store.path("install.json")
        if not path.exists():
            return {"plugin": PLUGIN, "version": VERSION, "installation_id": uuid.uuid4().hex,
                    "jobs": {}, "fixed": {}, "scripts": []}
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("plugin") != PLUGIN:
            raise ValueError("An unrelated installation record occupies muse/install.json")
        return data

    def save_manifest(self, manifest):
        manifest["version"] = VERSION
        self.store.write_text("install.json", json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")

    def _launcher(self, key, record):
        relative = f"scripts/hermes-muse-{key}.py"
        path = self.home / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink() or not path.resolve().is_relative_to(self.home):
            raise ValueError("Cron launcher escapes the active profile")
        content = (
            "# Generated by hermes-muse; owned entrypoint, not user code.\n"
            "import json\nfrom pathlib import Path\nimport runpy\n"
            f"entry = Path({str(self.root / 'cron_entry.py')!r})\n"
            "if not entry.is_file():\n    print(json.dumps({'wakeAgent': False}))\n"
            "else:\n    runpy.run_path(str(entry), init_globals={"
            f"'MUSE_HOME': str(Path(__file__).resolve().parent.parent), 'MUSE_JOB': {key!r}"
            "}, run_name='__main__')\n"
        )
        if path.exists() and relative not in record["scripts"] and not path.read_text(encoding="utf-8").startswith("# Generated by hermes-muse;"):
            raise ValueError(f"Refusing to overwrite an existing unrelated script: {path}")
        temporary = path.with_suffix(".tmp")
        if temporary.is_symlink():
            raise ValueError("Unsafe temporary launcher path")
        temporary.write_text(content, encoding="utf-8")
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
        if relative not in record["scripts"]:
            record["scripts"].append(relative)
        return path.name

    def _owned_job(self, key, options, *, owner=None, item=None, fixed=False, expires=None):
        from cron.jobs import create_job, list_jobs, update_job
        with profile_scope(self.home), file_lock(self.store.path("install.lock")):
            record = self.manifest()
            marker = f"[hermes-muse:{record['installation_id']}:{key}]"
            existing = None
            for job in list_jobs(include_disabled=True):
                if marker not in job.get("prompt", ""):
                    continue
                if fixed or job.get("state") not in {"completed", "failed", "cancelled"} and job.get("next_run_at"):
                    existing = job
                    break
            script = self._launcher(key, record)
            prompt = marker + "\n" + options.pop("prompt", "")
            if existing:
                if fixed:
                    # Refresh shipped instructions while preserving user pause/schedule/model choices.
                    existing = update_job(existing["id"], {"prompt": prompt, "script": script,
                                                           "skills": [f"{PLUGIN}:companion"], "workdir": None})
                job = existing
            else:
                job = create_job(prompt=prompt, script=script, **options)
            record["jobs"][job["id"]] = {"key": key, "owner": owner, "item": item, "marker": marker, "expires": expires}
            if fixed:
                record["fixed"][key] = job["id"]
            self.save_manifest(record)
            return job

    def default_deliver(self, detect_home=True):
        """Determine default delivery destination for proactive and governance jobs.

        Precedence:
        1. Explicit 'deliver' configured in PROACTIVE_PREFERENCES.md.
        2. 'all' if a gateway home channel is configured via /sethome.
        3. Fallback to 'bot-chat' for local/desktop environments.

        detect_home=False skips step 2. Plugin load must not ask Hermes for home channels: that lookup
        resolves gateway platform plugins, which wait on the plugin load already in progress (load timeout).
        """
        try:
            prefs_path = self.store.path("PROACTIVE_PREFERENCES.md")
            if prefs_path.is_file():
                line = prefs_path.read_text(encoding="utf-8").splitlines()[0]
                prefix = "<!-- hermes-muse "
                if line.startswith(prefix) and line.endswith(" -->"):
                    data = json.loads(line[len(prefix):-4])
                    deliver = data.get("deliver")
                    if deliver and isinstance(deliver, str) and deliver.strip():
                        return deliver.strip()
        except Exception:
            pass
        if not detect_home:
            return "bot-chat"
        try:
            from cron.scheduler_delivery import _iter_home_target_platforms, _get_home_target_chat_id
            if any(_get_home_target_chat_id(p) for p in _iter_home_target_platforms()):
                return "all"
        except Exception:
            pass
        return "bot-chat"

    def initialize(self):
        from hermes_cli.plugins import PluginContext
        if not callable(getattr(PluginContext, "register_system_prompt_section", None)):
            raise RuntimeError("Hermes lacks register_system_prompt_section; update Hermes")
        with file_lock(self.store.path("install.lock")):
            from .migration import migrate
            migrate(self.store)
            record = self.manifest()
            self.save_manifest(record)  # identity is durable before any external job creation
            # Legacy jobs already carry our installation marker; migrate in place, including watches.
            from cron.jobs import update_job
            with profile_scope(self.home):
                for job_id in record["jobs"]:
                    job = self.owned_job(job_id)
                    if job and job.get("workdir") is not None:
                        update_job(job_id, {"workdir": None})
            # Only a byte-identical shipped default is migrated; custom preferences survive.
            prefs_path = self.store.path("PROACTIVE_PREFERENCES.md")
            template = (self.root / "templates/PROACTIVE_PREFERENCES.md").read_text(encoding="utf-8")
            old_default = template.replace('"ordinary_per_day": null', '"ordinary_per_day": 1')
            if (prefs_path.exists() and prefs_path.read_text(encoding="utf-8") == old_default
                    and not self.store.read("meta", "explicit_preferences", {})):
                self.store.write_text("PROACTIVE_PREFERENCES.md", template)
                self.store.write("meta", "ordinary_default_upgrade", {"at": time.time(), "from": 1, "to": None})
            for file in (self.root / "templates").rglob("*.md"):
                relative = file.relative_to(self.root / "templates").as_posix()
                content = file.read_text(encoding="utf-8").replace("{{MUSE_HOME}}", str(self.store.root)).replace("{{HERMES_HOME}}", str(self.home))
                self.store.write_text(relative, content, create_only=True)
            for folder in ("memory/people", "memory/groups", "dreams/alignment/derived", "workspace/goals", "workspace/your_files/feed"):
                self.store.path(folder).mkdir(parents=True, exist_ok=True)
        default_destination = self.default_deliver(detect_home=False)
        for key, schedule in JOBS.items():
            prompt = (self.root / "prompts" / f"{key}.md").read_text(encoding="utf-8")
            self._owned_job(key, {"name": "muse-" + key, "schedule": schedule,
                                  "prompt": prompt, "skills": [f"{PLUGIN}:companion"],
                                  "deliver": default_destination if key in (*GOVERNANCE_JOBS, "proactive-watch") else "local",
                                  "attach_to_session": False}, fixed=True)
        # Upgrade the old silent patrol once; later user destination changes are preserved.
        from cron.jobs import get_job, update_job
        with profile_scope(self.home), file_lock(self.store.path("install.lock")):
            record = self.manifest()
            if not record.get("direct_patrol_delivery"):
                job = get_job(record["fixed"]["proactive-watch"])
                if job and job.get("deliver") == "local":
                    update_job(job["id"], {"deliver": "bot-chat"})
                old = ("Check its status and your stop condition first. Never send directly; prepare evidence with notification_add and notification_queue. "
                       "Stop and call watch_stop when the promised condition is satisfied. Return [SILENT].\n")
                for job_id, owned in record["jobs"].items():
                    if not owned["key"].startswith("watch-"):
                        continue
                    watch = get_job(job_id)
                    if watch and owned.get("owner") and old in watch.get("prompt", ""):
                        update_job(job_id, {"prompt": watch["prompt"].replace(old, watch_instructions(owned['key'], owned['owner']), 1),
                                            "deliver": "bot-chat" if watch.get("deliver") == "local" else watch.get("deliver")})
                record["direct_patrol_delivery"] = True
                self.save_manifest(record)
        return self.manifest()

    def wake(self, key):
        from cron.jobs import get_job, update_job
        with profile_scope(self.home):
            job_id = self.manifest()["fixed"].get(key)
            job = get_job(job_id) if job_id else None
            if job and job.get("enabled"):
                at = stamp(time.time())
                # Native due scans re-anchor off-schedule times unless marked as a manual fire.
                # Preserve enabled/state here: a concurrent user pause must not be undone.
                update_job(job_id, {"next_run_at": at, "manual_run_at": at})
                return True
        return False

    def signal_original(self, row):
        """Resolve a legacy excerpt without loading the conversation's entire later history."""
        from .operations import GROUPS, reader
        from .store import digest
        path = self.home / "state.db"
        if not path.exists():
            return {"available": False, "messages": []}
        with reader(path) as db:
            session = db.execute("SELECT chat_type FROM sessions WHERE id=?", (row["session_id"],)).fetchone()
            if not session or str(session["chat_type"] or "").lower() in GROUPS:
                return {"available": False, "messages": []}
            columns = {col[1] for col in db.execute("PRAGMA table_info(messages)")}
            uid = "message_uid" if "message_uid" in columns else "NULL AS message_uid"
            active = "AND (active=1 OR compacted=1) " if {"active", "compacted"} <= columns else ""
            matches = {}
            for message in db.execute(
                    f"SELECT id,content,timestamp,{uid} FROM messages WHERE session_id=? "
                    "AND role='user' AND timestamp BETWEEN ? AND ? "
                    "AND COALESCE(display_kind,'')!='hidden' AND (tool_calls IS NULL OR tool_calls='[]') "
                    + active + "ORDER BY id",
                    (row["session_id"], row["created"] - 300, row["created"] + 300)):
                text = message["content"]
                if isinstance(text, str) and text.startswith(row["text"]):
                    # Compression copies share a UID; distinct real turns remain ambiguous.
                    key = (message["message_uid"] or message["id"], digest(text))
                    matches.setdefault(key, {"id": message["id"], "role": "user", "text": text, "at": message["timestamp"]})
        return {"available": True, "messages": list(matches.values())}

    def conversation(self, session_id, since):
        from .conversation import read_conversation
        with profile_scope(self.home):
            return read_conversation(self.home, session_id, since)

    def route(self, session_id=None):
        from cron.scheduler_delivery import BOT_CHAT_PLATFORM
        # Bare bot-chat resolves against this job's profile, never another profile's Bot Chat.
        return {"deliver": BOT_CHAT_PLATFORM}

    def current_delivery(self, task_id):
        """Bind a prepared notice to the host-supplied, currently running Cron attempt."""
        from cron.executions import get_execution
        parts = str(task_id or "").split(":", 2)
        if len(parts) != 3 or parts[0] != "cron":
            return None
        _, job_id, execution_id = parts
        owned = self.manifest()["jobs"].get(job_id, {})
        key = owned.get("key", "")
        if key not in ("proactive-watch", *GOVERNANCE_JOBS) and not key.startswith("watch-"):
            return None
        with profile_scope(self.home):
            job, execution = self.owned_job(job_id), get_execution(execution_id)
        if (not job or job.get("deliver") in (None, "local") or not execution
                or execution.get("job_id") != job_id or execution.get("status") != "running"):
            return None
        return {"job_id": job_id, "execution_id": execution_id, "route": {"deliver": job["deliver"]},
                "kind": "report" if key in GOVERNANCE_JOBS else "notice"}

    def watch(self, data):
        goal, _ = self.store.goal(data["goal_id"])
        if goal["status"] != "active":
            raise ValueError("A watch requires an active goal")
        with self.store.transaction() as db:
            Companion(self.store, self).require_signal(db, data.get("signal_id"))
        expires = epoch(data["expires"]) if data.get("expires") else goal.get("deadline")
        if expires is not None and expires <= time.time():
            raise ValueError("Watch expiry must be in the future")
        from .store import bounded
        prompt_text = bounded(data.get("prompt"), 4000)
        stop = bounded(data.get("stop_condition"), 4000)
        from .scheduling import validate_watch
        validate_watch(data.get("schedule", "every 30m"))
        if self.manifest().get("preparation"):
            raise ValueError("Installation is prepared for disable/remove; no new watch allowed")
        key = "watch-" + uuid.uuid4().hex[:12]
        prompt = ("Read hermes-muse:companion including its execution/recovery and communication procedures, and muse_manage context. Work only on goal " + goal["id"] + ". "
                  + watch_instructions(key, goal["id"])
                  + prompt_text + "\nStop condition: " + stop)
        job = self._owned_job(key, {"name": "muse-" + key, "schedule": data.get("schedule", "every 30m"), "prompt": prompt,
                                   "skills": [f"{PLUGIN}:companion"], "deliver": self.default_deliver()}, owner=goal["id"], expires=expires)
        with file_lock(self.store.path("install.lock")):
            manifest = self.manifest()
            manifest["jobs"][job["id"]]["stop_condition"] = stop
            self.save_manifest(manifest)
        return job

    def owned_job(self, job_id):
        from cron.jobs import get_job
        manifest = self.manifest()
        owned = manifest["jobs"].get(job_id, {})
        marker = owned.get("marker", "")
        with profile_scope(self.home):
            job = get_job(job_id)
        if (marker != f"[hermes-muse:{manifest['installation_id']}:{owned.get('key')}]" or not job
                or marker not in job.get("prompt", "")):
            return None
        return job

    def is_active_watch(self, job_id, goal_id):
        record = self.manifest()["jobs"].get(job_id)
        if not record or not record["key"].startswith("watch-") or record.get("owner") != goal_id:
            return False
        if record.get("expires") is not None and record["expires"] <= time.time():
            return False
        with profile_scope(self.home):
            job = self.owned_job(job_id)
        return bool(job and job.get("enabled"))

    def pause_owner(self, owner):
        from cron.jobs import pause_job
        with profile_scope(self.home):
            for job_id, record in self.manifest()["jobs"].items():
                if record.get("owner") != owner:
                    continue
                if record.get("item"):
                    row = self.store.read("notification", record["item"], {})
                    if row.get("final_result"):
                        continue
                job = self.owned_job(job_id)
                # Hermes refuses pause_job on a finished one-shot; nothing is left to pause.
                if job and job.get("state") not in {"completed", "error"}:
                    pause_job(job_id, reason="Hermes Muse: owning goal closed")

    def stop_watch(self, job_id):
        from cron.jobs import pause_job
        owned = self.manifest()["jobs"].get(job_id)
        if not owned or not owned["key"].startswith("watch-") or not self.owned_job(job_id):
            raise ValueError("Not a plugin-owned watch")
        with profile_scope(self.home):
            return pause_job(job_id, reason="Hermes Muse: watch completed or cancelled")

    def reconcile(self):
        from cron.executions import latest_execution
        updates = []
        for row in self.store.all("notification"):
            reconcilable = row["status"] in {"dispatching", "queued", "transport_queued"}
            reconcilable |= bool(row["status"] == "unknown" and row.get("direct_delivery") and row.get("output_finalized"))
            if not reconcilable or not row.get("job_id"):
                continue
            with profile_scope(self.home):
                if row.get("direct_delivery"):
                    from cron.executions import get_execution
                    execution = get_execution(row["execution_id"])
                else:
                    execution = latest_execution(row["job_id"])
            if not execution or execution["status"] in {"claimed", "running"}:
                continue
            outcome = execution.get("delivery_outcome")
            if row.get("direct_delivery") and not row.get("output_finalized"):
                status = "unknown"  # a delivered status summary is not delivery of the notice body
            elif row["status"] == "queued":
                # The script was never entered: preparation failed, no receipt is implied.
                status = "failed" if execution["status"] == "failed" else "unknown"
            elif execution["status"] == "completed" and outcome == "delivered":
                status = "sent"
            elif outcome == "queued" and row.get("route", {}).get("deliver") == "bot-chat":
                status = self.bot_delivery_status(row["job_id"], row.get("execution_id") if row.get("direct_delivery") else None)
            elif outcome == "queued":
                from cron.delivery_queue import get_status
                with profile_scope(self.home):
                    receipt = get_status(execution["id"])
                queue_status = (receipt or {}).get("status")
                status = "sent" if queue_status == "delivered" else "unknown" if queue_status in {"failed", "unknown", "suppressed"} else "transport_queued"
            else:
                status = "unknown"  # including partial sends/timeouts: never blindly replay
            row_before_status = row["status"]
            before = dict(row)
            if status == "failed" and row_before_status == "queued" and not row.get("output_finalized"):
                row["definitive_not_accepted"] = True
            row.update(status=status, execution_id=execution["id"], delivery_outcome=outcome,
                       delivery_note="Native transport report; not a phone display/read receipt.")
            if row == before:
                continue  # Rewriting an unchanged row bumps _revision and expires every notice cursor.
            with self.store.transaction() as db:
                current = self.store.get(db, "notification", row["id"])
                if current and current["status"] == row_before_status:
                    self.store.put(db, "notification", row["id"], row)
            updates.append(row)
        return updates

    def bot_delivery_status(self, job_id, execution_id=None):
        from cron.jobs import get_job
        from cron.bot_chat_delivery import read_pending
        from tools.bot_live_delivery import read_delivery_result
        with profile_scope(self.home):
            if execution_id:
                # Mirrors the native same-profile Bot Chat key on the tested Hermes baseline.
                # Read only: a missing/changed host receipt never authorizes a resend.
                key = bot_receipt_key(self.home, job_id, execution_id)
                actual = read_delivery_result(self.home, key) or read_pending(key)
                if actual:
                    return bot_receipt_status([actual.get("status")])
                from cron.executions import latest_execution
                latest = latest_execution(job_id)
                if not latest or latest["id"] != execution_id:
                    return "unknown"
            job = get_job(job_id)
            if not job:
                return "unknown"
            receipts = job.get("last_delivery_queued") or {}
            if not receipts:
                return "unknown"  # no receipt id means no evidence of admission or completion
            states = []
            for receipt in receipts.values():
                key = receipt.get("delivery_id")
                if not key:
                    return "unknown"
                actual = read_delivery_result(self.home, key) or read_pending(key) or {}
                states.append(actual.get("status"))
        return bot_receipt_status(states)

    def local_now(self, timestamp):
        from hermes_time import now
        with profile_scope(self.home):
            return datetime.fromtimestamp(timestamp, now().tzinfo)


def bot_receipt_key(home, job_id, execution_id):
    home = str(Path(home).resolve())
    return hashlib.sha256(json.dumps([home, job_id, str(execution_id), home],
                                    ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def bot_receipt_status(states):
    if states and all(state == "settled" for state in states):
        return "sent"
    if states and all(state in {"settled", "queued", "claimed", "transferred"} for state in states):
        return "transport_queued"
    return "unknown"


def enabled(home):
    """Read host consent; removal/disable must make remaining launchers harmless."""
    from hermes_cli.config import load_config
    with profile_scope(home):
        cfg = load_config()
    plugins = cfg.get("plugins", {})
    return PLUGIN in plugins.get("enabled", []) and PLUGIN not in plugins.get("disabled", [])


def wake_gate_settings(home):
    """`plugins.hermes-muse.wake_gate` from the profile config; any problem means the gate is off."""
    from . import wake_gate
    try:
        from hermes_cli.config import load_config
        with profile_scope(home):
            cfg = load_config()
        return wake_gate.settings(cfg.get("plugins", {}).get(PLUGIN, {}).get("wake_gate"))
    except Exception:
        return wake_gate.settings(None)


def cron_run(home, key):
    if not enabled(home):
        return {"wakeAgent": False, "reason": "plugin absent or disabled"}
    store = Store(home)
    host = HermesHost(store)
    service = Companion(store, host)
    host.reconcile()
    if key.startswith("deliver-"):
        notice_id = key[len("deliver-"):]
        text = service.delivery_text(notice_id)
        if not text:
            return ""
        notice = store.read("notification", notice_id, {})
        if notice.get("route", {}).get("deliver") != "bot-chat":
            return text  # already queued deliveries keep their original destination
        return ("[Hermes Muse notification " + notice_id + "]\n"
                "This is a prepared Cron result, not a new user request. Read the result and report it "
                "once in this Bot Chat. Do not create or queue another notification for this delivery.\n"
                "Why: " + notice.get("rationale", "") + "\n"
                "Sources: " + ", ".join(notice.get("sources", [])) + "\n\n" + text)
    if key.startswith("watch-"):
        pair = next(((jid, r) for jid, r in host.manifest()["jobs"].items() if r["key"] == key), None)
        owned = pair[1] if pair else None
        if not owned:
            return {"wakeAgent": False}
        if owned.get("expires") is not None and owned["expires"] <= time.time():
            host.stop_watch(pair[0])
            return {"wakeAgent": False, "reason": "watch expired"}
        try:
            goal, _ = store.goal(owned["owner"])
            return {"wakeAgent": goal["status"] == "active", "goal": goal["id"], "watch_id": pair[0]}
        except ValueError:
            return {"wakeAgent": False}
    # Fixed jobs must inspect live sources/memory before deciding there is no work.
    # Only owned watches retain their explicit lifecycle gate above.
    result = {"wakeAgent": key in JOBS, "job": key, "started_at": stamp(),
              "instruction": "Call muse_manage context, inspect current sources using this job's Skill, then decide whether there is useful work. No worthwhile notification means [SILENT], not a skipped check."}
    # Optional and off by default; fails open (see wake_gate.py).
    from . import wake_gate
    return wake_gate.apply(store, key, result, wake_gate_settings(home))
