"""Hermes Cron: plugin-owned jobs and their executions; delivery as one-shot no-agent jobs.

A job is owned when its script is a generated `hermes-muse-*.py` launcher in `<home>/scripts`.
Jobs never get a `workdir`: on Docker/remote terminals a host path breaks every command (0.3.2),
and launchers use absolute paths, so the process cwd is never needed.
"""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import time
from contextlib import contextmanager
from datetime import datetime, timedelta
from pathlib import Path

from . import HOST_ERROR, Part, tolerant

KEY = re.compile(r"[a-z0-9][a-z0-9_-]{0,63}")
PREFIX = "hermes-muse-"
HEADER = "# Generated by hermes-muse; owned entrypoint, not user code.\n"
KNOWN_OUTCOMES = {None, "delivered", "queued", "failed", "suppressed", "suppressed_acked", "not_configured"}
FINISHED = {"completed", "error"}


def epoch(stamp):
    return datetime.fromisoformat(stamp).timestamp() if stamp else None


def owned(job):
    return str(job.get("script") or "").startswith(PREFIX)


def check_key(key):
    if not KEY.fullmatch(str(key)):
        raise ValueError(f"Invalid Muse job key: {key!r}")
    return key


class Cron(Part):
    @contextmanager
    def lock(self):
        path = self.home / "muse" / "host.lock"
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "a") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            yield

    def write_script(self, name, body):
        """Atomically write an owned launcher; never overwrite a file Muse did not generate."""
        path = self.home / "scripts" / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_symlink() or (path.exists() and not path.read_text(encoding="utf-8").startswith(HEADER)):
            raise ValueError(f"Refusing to overwrite an unrelated script: {path}")
        temporary = path.with_name(name + ".tmp")
        temporary.write_text(HEADER + body, encoding="utf-8")
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
        return name

    def owned_jobs(self):
        from cron.jobs import list_jobs
        with self.scope():
            return {job["id"]: job for job in list_jobs(include_disabled=True) if owned(job)}

    @tolerant(dict)
    def jobs(self):
        """Owned jobs by id, including paused and finished ones."""
        return self.owned_jobs()

    def by_script(self, script):
        # Raises on a host failure: an empty answer here would create a duplicate job or resend.
        return next((job for job in self.owned_jobs().values() if job.get("script") == script), None)

    @tolerant(lambda: None)
    def ensure(self, key, *, schedule, entry, prompt=None, deliver="local", skills=None, no_agent=False):
        """Create or refresh owned job `muse-<key>`; a refresh keeps the user's schedule, route, pause and model.

        The launcher runs `entry` (absolute) with MUSE_HOME and MUSE_JOB; a missing entry means `wakeAgent: false`.
        """
        check_key(key)
        entry = Path(entry)
        if not entry.is_absolute():
            raise ValueError("Cron entry must be an absolute path")
        body = ("import json, runpy\nfrom pathlib import Path\n"
                f"entry = Path({str(entry)!r})\n"
                "if not entry.is_file():\n    print(json.dumps({'wakeAgent': False}))\n"
                "else:\n    runpy.run_path(str(entry), init_globals={"
                f"'MUSE_HOME': {str(self.home)!r}, 'MUSE_JOB': {key!r}}}, run_name='__main__')\n")
        from cron.jobs import create_job, update_job
        with self.lock():
            script = self.write_script(f"{PREFIX}{key}.py", body)
            existing = self.by_script(script)
            with self.scope():
                if existing:
                    return update_job(existing["id"], {"prompt": prompt, "skills": skills or [], "workdir": None})
                return create_job(prompt=prompt, schedule=schedule, name=f"muse-{key}", deliver=deliver,
                                  skills=skills, script=script, no_agent=no_agent)

    @tolerant(False)
    def pause(self, job_id, reason):
        """Pause an owned job; a finished one-shot has nothing left to pause."""
        job = self.jobs().get(job_id)
        if not job or job.get("state") in FINISHED:
            return False
        from cron.jobs import pause_job
        with self.scope():
            return bool(pause_job(job_id, reason=f"Hermes Muse: {reason}"))

    @tolerant(False)
    def resume(self, job_id):
        """Resume an owned paused job (rollback of a Muse pause)."""
        if job_id not in self.jobs():
            return False
        from cron.jobs import resume_job
        with self.scope():
            return bool(resume_job(job_id))

    @tolerant(False)
    def set_prompt(self, job_id, prompt):
        """Replace an owned job's prompt only; schedule, route and pause stay (rollback restores 0.3.x prompts)."""
        if job_id not in self.jobs():
            return False
        from cron.jobs import update_job
        with self.scope():
            return bool(update_job(job_id, {"prompt": prompt}))

    @tolerant(False)
    def wake(self, job_id):
        """Run an enabled owned job now as a manual fire; pause and schedule stay as they are."""
        job = self.jobs().get(job_id)
        if not job or not job.get("enabled"):
            return False
        from cron.jobs import update_job
        at = datetime.now().astimezone().isoformat()
        with self.scope():
            return bool(update_job(job_id, {"next_run_at": at, "manual_run_at": at}))

    @tolerant(lambda: {"execution_id": None, "status": HOST_ERROR})
    def outcome(self, job_id, execution_id=None):
        """One execution (default: latest) as {execution_id, status, delivery_outcome, error, start, end};
        None when the host has no such execution, status host_error when it could not be read."""
        from cron.executions import get_execution, latest_execution
        with self.scope():
            row = get_execution(execution_id) if execution_id else latest_execution(job_id)
        return shape(row) if row and row["job_id"] == job_id else None

    @tolerant(list)
    def executions(self, since):
        """Executions of owned jobs claimed after `since`, newest first per job."""
        from cron.executions import list_executions
        rows = []
        for job_id in self.jobs():
            with self.scope():
                page = list_executions(job_id=job_id, limit=500)
            rows += [shape(row) for row in page if (epoch(row["claimed_at"]) or 0) > since]
        return rows


def shape(row):
    start = epoch(row.get("started_at") or row.get("claimed_at"))
    return {"execution_id": row["id"], "job_id": row["job_id"], "status": row["status"],
            "delivery_outcome": row.get("delivery_outcome"), "error": row.get("error"),
            "start": start, "end": epoch(row.get("finished_at")) or time.time()}


def bot_receipt_key(source_home, job_id, execution_id, target_home):
    """The native Bot Chat delivery id of one cron run (cron.scheduler_delivery._deliver_to_bot_chat)."""
    return hashlib.sha256(json.dumps([str(source_home), job_id, str(execution_id), str(target_home)],
                                     ensure_ascii=False, separators=(",", ":")).encode()).hexdigest()


def failure_reason(text):
    text = str(text or "")
    return "host_config" if "cwd" in text or "invalid_params" in text or "not_configured" in text else "transport"


class Deliver(Part):
    @tolerant(lambda: {"status": "failed", "reason": "host_error"})
    def send(self, target, text, key):
        """Deliver `text` once to a Hermes route (`bot-chat`, `bot-chat:<profile>`, `telegram`, …).

        A one-shot no-agent job prints the text and deletes its script, so a host retry cannot resend.
        A repeated `key` returns the existing receipt instead of sending again.
        """
        check_key(key)
        if not isinstance(text, str) or not text.strip():
            raise ValueError("Delivery text is empty")
        cron = self.adapter.cron
        from cron.jobs import create_job
        with cron.lock():
            if cron.by_script(f"{PREFIX}deliver-{key}.py"):
                return self.receipt(key)
            script = cron.write_script(f"{PREFIX}deliver-{key}.py", (
                "from pathlib import Path\n"
                f"print({text!r})\n"
                "Path(__file__).unlink(missing_ok=True)\n"))
            at = (datetime.now().astimezone() + timedelta(seconds=5)).isoformat(timespec="seconds")
            with self.scope():
                job = create_job(prompt=None, schedule=at, name=f"muse-deliver-{key}", deliver=target,
                                 script=script, no_agent=True)
        return {"status": "sending", "job_id": job["id"]}

    @tolerant(lambda: {"status": "unknown", "reason": "host_error"})
    def receipt(self, key):
        """sending | sent | failed(reason: host_config/transport/run_failed) | unknown. Read-only; never resends."""
        job = self.adapter.cron.by_script(f"{PREFIX}deliver-{check_key(key)}.py")
        if not job:
            return {"status": "unknown", "reason": "no_delivery_job"}
        run = self.adapter.cron.outcome(job["id"])
        if run and run["status"] == HOST_ERROR:
            return {"status": "unknown", "reason": HOST_ERROR}  # notifier.apply leaves the notice for the next tick
        base = {"job_id": job["id"], **({"execution_id": run["execution_id"], "outcome": run["delivery_outcome"]} if run else {})}
        if not run or run["status"] in ("claimed", "running"):
            return {**base, "status": "sending"}
        status, detail = self.classify(job, run)
        if status == "failed":
            return {**base, "status": "failed", "reason": failure_reason(detail) if run["status"] != "failed" else "run_failed",
                    "detail": str(detail or "")[:500]}
        return {**base, "status": status}

    def classify(self, job, run):
        """(status, detail) of a finished run from the ledger outcome and, when queued, the native receipt."""
        outcome = run["delivery_outcome"]
        if run["status"] == "failed":
            return "failed", run["error"]
        if outcome == "delivered":
            return "sent", None
        if outcome in ("failed", "not_configured"):
            return "failed", job.get("last_delivery_error") or outcome
        if outcome != "queued":
            return "unknown", outcome
        target = str(job.get("deliver") or "")
        if target.startswith("bot-chat"):
            receipt = self.bot_receipt(target, job["id"], run["execution_id"])
            state = (receipt or {}).get("status")
            if state == "settled":
                return "sent", None
            if state in ("queued", "claimed", "transferred"):
                return "sending", None
            if state in ("refused", "failed"):
                return "failed", receipt.get("error") or receipt.get("reason")
            return "unknown", state
        from cron.delivery_queue import get_status
        with self.scope():
            state = (get_status(run["execution_id"]) or {}).get("status")
        return {"delivered": ("sent", None), "failed": ("failed", "delivery queue failed"),
                "unknown": ("unknown", state), "suppressed": ("unknown", state)}.get(state, ("sending", None))

    def bot_receipt(self, target, job_id, execution_id):
        """Native Bot Chat receipt (live or deferred) for one run, or None when unreadable."""
        profile = target.partition(":")[2]
        target_home = self.home
        if profile:
            from hermes_cli.profiles import get_profile_dir
            target_home = Path(get_profile_dir(profile)).resolve()
        key = bot_receipt_key(self.home, job_id, execution_id, target_home)
        from tools.bot_live_delivery import read_delivery_result
        with self.scope():
            found = read_delivery_result(target_home, key)
        if found:
            return found
        pending = self.home / "cron" / "bot_chat_pending" / f"{key}.json"  # cron.bot_chat_legacy.defer: source home
        return json.loads(pending.read_text(encoding="utf-8-sig")) if pending.is_file() else None
